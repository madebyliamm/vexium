#!/usr/bin/env node
// Embeds sdk/v1.js into the publisher Worker (publisher/src/sdk.generated.ts).
// Run after every edit of sdk/v1.js, then redeploy the Worker:
//   node scripts/build-sdk.mjs && npx wrangler deploy --config publisher/wrangler.toml --keep-vars
// publisher/test checks that the committed output matches the source, so a forgotten rebuild fails the tests.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../sdk/v1.js', import.meta.url), 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 10);

const out = `// GENERATED by scripts/build-sdk.mjs from sdk/v1.js — do not edit by hand.
export const SDK_V1_HASH = ${JSON.stringify(hash)};
export const SDK_V1_SOURCE = ${JSON.stringify(src)};
`;
writeFileSync(new URL('../publisher/src/sdk.generated.ts', import.meta.url), out);
console.log(`sdk/v1.js (${src.length} bytes) -> publisher/src/sdk.generated.ts  hash ${hash}`);
