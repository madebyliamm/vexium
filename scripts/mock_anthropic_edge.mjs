#!/usr/bin/env node
// Writes supabase/functions/mock-anthropic/index.ts from cf-worker/mock/anthropic.ts, so the stand-in for Anthropic can ALSO be served
// from a Supabase edge function. Why: the build Worker's streaming path (PLAN / EXAMPLE / TWEAKS) cannot call another *.workers.dev Worker
// (Cloudflare error 1042); only the FULL BUILD Workflow can. See docs/INFRA.md "Testing the build without Anthropic credit".
//   node scripts/mock_anthropic_edge.mjs && supabase functions deploy mock-anthropic --no-verify-jwt --project-ref ciuqhxrxcznmgorjeumz
//   …test…  supabase functions delete mock-anthropic --project-ref ciuqhxrxcznmgorjeumz && rm -r supabase/functions/mock-anthropic
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const REPO = resolve(import.meta.dirname, '..');
let src = readFileSync(join(REPO, 'cf-worker/mock/anthropic.ts'), 'utf8');
if (!src.includes('export default {')) throw new Error('cf-worker/mock/anthropic.ts no longer has `export default {`');
src = src.replace('export default {', 'const mock = {')
  .replace("url.pathname !== '/v1/messages'", "!url.pathname.endsWith('/v1/messages')");
src += '\nDeno.serve((req) => mock.fetch(req));\n';
mkdirSync(join(REPO, 'supabase/functions/mock-anthropic'), { recursive: true });
writeFileSync(join(REPO, 'supabase/functions/mock-anthropic/index.ts'), '// GENERATED by scripts/mock_anthropic_edge.mjs — temporary test function, never commit.\n// @ts-nocheck\n' + src);
console.log('wrote supabase/functions/mock-anthropic/index.ts');
