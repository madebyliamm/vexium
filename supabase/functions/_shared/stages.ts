// The Vertly stage engine, as pure TypeScript — no imports, no I/O, so the SAME file runs in the studio (Vite), in the edge
// functions (Deno) and in the Node unit tests. Don't add a dependency here.
//
// The rules are mirrored from the database: supabase/migrations/20261014100000_stage_engine.sql keeps them in ONE jsonb literal
// (vx_stage_rules) and supabase/tests/stages.test.ts fails if STAGE_RULES below ever differs from it. The database is the
// authority (set_project_stage / put_project_artifact enforce them); this module lets the UI and the AI endpoints answer the
// same questions without a round trip, and `applyPut` / `applyKeep` replay the stale-marking exactly as the RPCs do.
// Full description: docs/STAGES.md.

export const STAGES = ['plan', 'example', 'build', 'tweaks', 'launch', 'business'] as const;
export type Stage = (typeof STAGES)[number];

export const ARTIFACT_KINDS = ['plan', 'style_spec', 'manifest', 'launch_checks', 'business_state'] as const;
export type ArtifactKind = (typeof ARTIFACT_KINDS)[number];

/** MUST stay byte-for-byte equal (after JSON parsing) to the literal in vx_stage_rules(). */
export const STAGE_RULES = {
  stages: ['plan', 'example', 'build', 'tweaks', 'launch', 'business'],
  kinds: ['plan', 'style_spec', 'manifest', 'launch_checks', 'business_state'],
  /** Artifacts that must exist, be fresh (not stale) and carry their required flags before a project may ENTER a stage going forward. */
  requires: {
    plan: [],
    example: ['plan'],
    build: ['plan', 'style_spec'],
    tweaks: ['plan', 'style_spec', 'manifest'],
    launch: ['plan', 'style_spec', 'manifest', 'launch_checks'],
    business: [],
  },
  /** Stages that also need a live site (projects.published_version set). */
  requires_published: ['business'],
  /** kind → a boolean field of its data that must be true wherever the kind is required (the locked StyleSpec). */
  required_flags: { style_spec: 'locked' },
  /** Saving a new version of the key marks the latest version of every listed kind stale (transitive closure of DEPENDS_ON). */
  downstream: {
    plan: ['style_spec', 'manifest', 'launch_checks'],
    style_spec: ['manifest', 'launch_checks'],
    manifest: ['launch_checks'],
    launch_checks: [],
    business_state: [],
  },
  /** Kinds a signed-in project member may save. The rest are outputs of server-side work (service role only). */
  client_writable: ['plan', 'style_spec'],
  /** Kinds a member may mark "still fine" while stale. launch_checks / business_state must be regenerated by the platform. */
  client_keepable: ['plan', 'style_spec', 'manifest'],
  max_versions: 20,
  max_bytes: 262144,
} as const;

/** What each artifact is built from (direct edges). STAGE_RULES.downstream is the transitive closure; a test checks it. */
export const DEPENDS_ON: Record<ArtifactKind, readonly ArtifactKind[]> = {
  plan: [],
  style_spec: ['plan'],
  manifest: ['plan', 'style_spec'],
  launch_checks: ['manifest'],
  business_state: [],
};

/**
 * What an AI run of each stage reads and writes.
 *  - inputs   : upstream artifacts, frozen while the stage runs → they go in the prompt-cached system block (must exist + be fresh)
 *  - worksOn  : the artifact the stage edits → changes every turn, so it goes in the NON-cached suffix
 *  - produces : the artifact an AI run of this stage can save (null = none; the platform computes it)
 */
export const STAGE_IO: Record<Stage, { inputs: readonly ArtifactKind[]; worksOn: ArtifactKind | null; produces: ArtifactKind | null }> = {
  plan: { inputs: [], worksOn: 'plan', produces: 'plan' },
  example: { inputs: ['plan'], worksOn: 'style_spec', produces: 'style_spec' },
  build: { inputs: ['plan', 'style_spec'], worksOn: 'manifest', produces: 'manifest' },
  tweaks: { inputs: ['plan', 'style_spec'], worksOn: 'manifest', produces: 'manifest' },
  launch: { inputs: ['manifest'], worksOn: 'launch_checks', produces: null },
  business: { inputs: ['plan', 'manifest'], worksOn: 'business_state', produces: null },
};

export const STAGE_LABELS: Record<Stage, string> = {
  plan: 'Plan',
  example: 'Example',
  build: 'Full build',
  tweaks: 'Tweaks',
  launch: 'Launch',
  business: 'Business',
};

export function isStage(x: unknown): x is Stage {
  return typeof x === 'string' && (STAGES as readonly string[]).includes(x);
}

export function isArtifactKind(x: unknown): x is ArtifactKind {
  return typeof x === 'string' && (ARTIFACT_KINDS as readonly string[]).includes(x);
}

export function stageRank(stage: Stage): number {
  return STAGES.indexOf(stage);
}

export function nextStage(stage: Stage): Stage | null {
  return STAGES[stageRank(stage) + 1] ?? null;
}

export function prevStage(stage: Stage): Stage | null {
  return STAGES[stageRank(stage) - 1] ?? null;
}

/** Latest version of one artifact, as the studio/edge functions hold it (`project_artifacts_latest`). */
export interface ArtifactSummary {
  version: number;
  stale: boolean;
  data: Record<string, unknown>;
}
export type LatestArtifacts = Partial<Record<ArtifactKind, ArtifactSummary>>;

export type BlockerKind = ArtifactKind | 'published';
/** missing | stale | flag:<field> (e.g. flag:locked) */
export type BlockerReason = 'missing' | 'stale' | `flag:${string}`;
export interface Blocker {
  kind: BlockerKind;
  reason: BlockerReason;
}

/** Why `target` can't be entered right now (empty = nothing in the way). Same answer as vx_stage_blockers() in SQL. */
export function blockers(target: Stage, latest: LatestArtifacts, published: boolean): Blocker[] {
  const out: Blocker[] = [];
  const flags: Record<string, string> = STAGE_RULES.required_flags;
  for (const kind of STAGE_RULES.requires[target] as readonly ArtifactKind[]) {
    const a = latest[kind];
    const flag = flags[kind];
    if (!a) out.push({ kind, reason: 'missing' });
    else if (a.stale) out.push({ kind, reason: 'stale' });
    else if (flag && a.data[flag] !== true) out.push({ kind, reason: `flag:${flag}` });
  }
  if ((STAGE_RULES.requires_published as readonly string[]).includes(target) && !published) {
    out.push({ kind: 'published', reason: 'missing' });
  }
  return out;
}

export interface MoveResult {
  ok: boolean;
  /** The stage the project is in after the call (the target when ok, otherwise unchanged). */
  stage: Stage;
  blockedBy: Blocker[];
}

/** Going back (or staying) is always allowed; going forward needs blockers() to be empty. Mirrors set_project_stage(). */
export function canMoveTo(current: Stage, target: Stage, latest: LatestArtifacts, published: boolean): MoveResult {
  if (stageRank(target) <= stageRank(current)) return { ok: true, stage: target, blockedBy: [] };
  const blockedBy = blockers(target, latest, published);
  return blockedBy.length ? { ok: false, stage: current, blockedBy } : { ok: true, stage: target, blockedBy: [] };
}

/** The furthest stage the project may enter right now (always ≥ current, because going back is free but staying is too). */
export function furthestEnterable(current: Stage, latest: LatestArtifacts, published: boolean): Stage {
  let best = current;
  for (const s of STAGES) if (stageRank(s) > stageRank(best) && canMoveTo(current, s, latest, published).ok) best = s;
  return best;
}

export function clientMayWrite(kind: ArtifactKind): boolean {
  return (STAGE_RULES.client_writable as readonly string[]).includes(kind);
}

export function clientMayKeep(kind: ArtifactKind): boolean {
  return (STAGE_RULES.client_keepable as readonly string[]).includes(kind);
}

/** Replays put_project_artifact(): a new fresh version of `kind`, and the latest version of each downstream kind flagged stale. */
export function applyPut(
  latest: LatestArtifacts,
  kind: ArtifactKind,
  data: Record<string, unknown>,
): { latest: LatestArtifacts; version: number; staled: ArtifactKind[] } {
  const next: LatestArtifacts = { ...latest };
  const version = (latest[kind]?.version ?? 0) + 1;
  next[kind] = { version, stale: false, data };
  const staled: ArtifactKind[] = [];
  for (const k of STAGE_RULES.downstream[kind] as readonly ArtifactKind[]) {
    const a = next[k];
    if (a && !a.stale) {
      next[k] = { ...a, stale: true };
      staled.push(k);
    }
  }
  return { latest: next, version, staled: staled.sort() };
}

/** Replays keep_project_artifact(): clears the stale flag on the latest version. */
export function applyKeep(latest: LatestArtifacts, kind: ArtifactKind): { latest: LatestArtifacts; cleared: boolean } {
  const a = latest[kind];
  if (!a || !a.stale) return { latest, cleared: false };
  return { latest: { ...latest, [kind]: { ...a, stale: false } }, cleared: true };
}

/** "kind:vN" per kind, "!" = stale, sorted — the same string the SQL test builds (supabase/tests/step7_stage_engine.sql). */
export function stateString(latest: LatestArtifacts): string {
  return ARTIFACT_KINDS.filter((k) => latest[k])
    .sort()
    .map((k) => `${k}:v${latest[k]!.version}${latest[k]!.stale ? '!' : ''}`)
    .join(',');
}

/** Human wording for a blocker, used by the studio ("Needs a plan first") and by error messages. */
export function describeBlocker(b: Blocker): string {
  const label: Record<BlockerKind, string> = {
    plan: 'your plan',
    style_spec: 'your style',
    manifest: 'the built site',
    launch_checks: 'the launch check',
    business_state: 'the business data',
    published: 'a live site',
  };
  const what = label[b.kind];
  if (b.reason === 'missing') return b.kind === 'published' ? 'Needs a live site first' : `Needs ${what} first`;
  if (b.reason === 'stale') return `${what[0]!.toUpperCase()}${what.slice(1)} is out of date — keep it or redo it`;
  if (b.reason === 'flag:locked') return 'Lock your style first';
  return `Needs ${what} (${b.reason})`;
}
